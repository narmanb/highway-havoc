#!/usr/bin/env python3
"""Synthesises every sound effect and the music loop for Highway Havoc.

All audio in assets/audio/ is generated by this script (original, no samples).
Run:  python3 tools/gen_audio.py      (requires numpy)
"""
import os
import wave
import numpy as np

SR = 22050
OUT = os.path.join(os.path.dirname(__file__), "..", "assets", "audio")
rng = np.random.default_rng(1234)


def t_axis(dur):
    return np.arange(int(SR * dur)) / SR


def env(n, a=0.005, d=0.1, s=0.0, r=0.0, total=None):
    """Simple attack/decay envelope over n samples."""
    x = np.arange(n) / SR
    e = np.minimum(x / max(a, 1e-4), 1.0)
    e *= np.where(x < a, 1.0, np.exp(-(x - a) / max(d, 1e-4)) * (1 - s) + s)
    return e


def square(freq, t, duty=0.5):
    ph = np.cumsum(np.broadcast_to(freq, t.shape) / SR)
    return np.where((ph % 1.0) < duty, 1.0, -1.0)


def tri(freq, t):
    ph = np.cumsum(np.broadcast_to(freq, t.shape) / SR)
    return 2 * np.abs(2 * (ph % 1.0) - 1) - 1


def sine(freq, t):
    ph = np.cumsum(np.broadcast_to(freq, t.shape) / SR)
    return np.sin(2 * np.pi * ph)


def noise(n):
    return rng.uniform(-1, 1, n)


def lowpass(x, k):
    """One-pole lowpass, k in (0,1]: smaller = darker."""
    y = np.zeros_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc += k * (x[i] - acc)
        y[i] = acc
    return y


def write(name, x, vol=0.8):
    x = np.asarray(x, dtype=np.float64)
    peak = np.max(np.abs(x)) or 1.0
    x = x / peak * vol
    data = (np.clip(x, -1, 1) * 32767).astype(np.int16)
    with wave.open(os.path.join(OUT, name + ".wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())


def sfx():
    t = t_axis(0.09)
    write("hop", square(np.linspace(520, 900, len(t)), t, 0.25) * env(len(t), 0.002, 0.03), 0.45)
    t = t_axis(0.2)
    write("dash", (square(np.linspace(300, 1400, len(t)), t, 0.3) * 0.6 + noise(len(t)) * 0.3) * env(len(t), 0.003, 0.08), 0.55)
    t = t_axis(0.12)
    write("bonk", tri(np.linspace(180, 90, len(t)), t) * env(len(t), 0.002, 0.05), 0.6)
    t = t_axis(0.45)
    f = 400
    honk = (square(f, t, 0.4) + square(f * 1.26, t, 0.4)) * env(len(t), 0.01, 0.6, 0.6)
    honk *= np.where(t < 0.38, 1.0, np.maximum(0, 1 - (t - 0.38) / 0.07))
    write("honk", lowpass(honk, 0.25), 0.55)
    t = t_axis(0.7)
    crash = noise(len(t)) * env(len(t), 0.001, 0.18) + sine(np.linspace(140, 40, len(t)), t) * env(len(t), 0.001, 0.12)
    clink = square(np.linspace(1800, 1200, len(t)), t, 0.5) * env(len(t), 0.001, 0.04) * 0.4
    write("crash", lowpass(crash, 0.5) + clink, 0.85)
    t = t_axis(0.5)
    skid = noise(len(t)) * env(len(t), 0.03, 0.3, 0.3)
    write("skid", lowpass(skid, 0.08) * square(np.full(len(t), 60.0), t) * 0.5 + lowpass(skid, 0.4) * 0.5, 0.4)
    t = t_axis(0.3)
    whoosh = lowpass(noise(len(t)), 0.12) * np.sin(np.pi * t / t[-1])
    write("nearmiss", whoosh + square(np.linspace(900, 1500, len(t)), t, 0.2) * env(len(t), 0.002, 0.06) * 0.3, 0.6)
    # Arpeggiated pickup chime
    parts = []
    for fr in (880, 1175, 1568):
        tt = t_axis(0.06)
        parts.append(square(fr, tt, 0.25) * env(len(tt), 0.001, 0.05))
    write("pickup", np.concatenate(parts), 0.45)
    t = t_axis(0.18)
    write("ride", square(np.linspace(300, 700, len(t)), t, 0.5) * env(len(t), 0.002, 0.08), 0.45)
    t = t_axis(0.15)
    write("button", (square(1046, t, 0.5) * (t < 0.06) + square(1568, t, 0.5) * (t >= 0.07)) * env(len(t), 0.001, 0.2), 0.4)
    t = t_axis(0.25)
    write("signal_wait", sine(740, t) * env(len(t), 0.005, 0.12), 0.4)
    # Accessible "walk" chirps
    chirps = []
    for _ in range(3):
        tt = t_axis(0.07)
        chirps.append(sine(np.linspace(1800, 2600, len(tt)), tt) * env(len(tt), 0.002, 0.04))
        chirps.append(np.zeros(int(SR * 0.05)))
    write("signal_walk", np.concatenate(chirps), 0.4)
    t = t_axis(0.3)
    write("signal_end", square(600, t, 0.5) * (np.sin(2 * np.pi * 12 * t) > 0) * env(len(t), 0.002, 0.25), 0.3)
    t = t_axis(0.25)
    write("respawn", square(np.linspace(400, 1200, len(t)), t, 0.125) * env(len(t), 0.005, 0.15), 0.4)
    # Delivery fanfare
    notes = [(523, 0.1), (659, 0.1), (784, 0.1), (1046, 0.35)]
    fan = []
    for fr, d in notes:
        tt = t_axis(d)
        fan.append((square(fr, tt, 0.25) * 0.6 + tri(fr / 2, tt) * 0.5) * env(len(tt), 0.003, d * 0.8, 0.3))
    write("deliver", np.concatenate(fan), 0.6)
    # Splash: noise burst with a falling "bloop"
    t = t_axis(0.6)
    sp = lowpass(noise(len(t)), 0.35) * env(len(t), 0.002, 0.18) + sine(np.linspace(500, 120, len(t)), t) * env(len(t), 0.01, 0.12) * 0.6
    write("splash", sp, 0.7)
    # Wooden plank thunk for landing on a floating platform
    t = t_axis(0.14)
    write("plank", (tri(np.linspace(220, 150, len(t)), t) + lowpass(noise(len(t)), 0.4) * 0.4) * env(len(t), 0.001, 0.04), 0.55)
    t = t_axis(0.1)
    write("ui_move", square(880, t, 0.25) * env(len(t), 0.001, 0.03), 0.3)
    t = t_axis(0.16)
    write("ui_select", square(np.where(t < 0.06, 660, 990), t, 0.25) * env(len(t), 0.001, 0.1), 0.35)


def music():
    """16-bar loop at 132 BPM: bass, arpeggio lead, drums."""
    bpm = 132
    beat = 60 / bpm
    step = beat / 4
    bars = 8
    n_steps = bars * 16
    total = int(SR * step * n_steps)
    out = np.zeros(total)
    # I - vi - IV - V in C, twice with a lift
    chords = [(48, [0, 4, 7]), (45, [0, 3, 7]), (41, [0, 4, 7]), (43, [0, 4, 7])] * 2
    def midi(m):
        return 440.0 * 2 ** ((m - 69) / 12)
    seg = int(SR * step)
    for s in range(n_steps):
        bar = s // 16
        root, tri_ = chords[bar]
        start = s * seg
        tt = np.arange(seg) / SR
        # Bass on 8ths with octave bounce
        if s % 2 == 0:
            m = root - 12 + (12 if (s // 2) % 2 else 0)
            out[start:start + seg] += tri(midi(m), tt) * env(seg, 0.002, step * 1.5) * 0.55
        # Arpeggio lead
        arp = tri_[(s + bar) % 3] + 12 + (12 if bar >= 4 and s % 8 >= 4 else 0)
        out[start:start + seg] += square(midi(root + arp + 12), tt, 0.25) * env(seg, 0.002, step * 0.6) * 0.16
        # Melody hook every other bar
        if bar % 2 == 1 and s % 16 in (0, 3, 6, 10, 12):
            mel = root + 24 + [7, 9, 7, 4, 2][[0, 3, 6, 10, 12].index(s % 16)]
            ln = min(seg * 3, total - start)
            t2 = np.arange(ln) / SR
            out[start:start + ln] += square(midi(mel), t2, 0.5) * env(ln, 0.004, step * 2) * 0.13
        # Drums
        if s % 8 == 0 or s % 16 == 10:
            k = sine(np.linspace(150, 45, seg), tt) * env(seg, 0.001, 0.06)
            out[start:start + seg] += k * 0.8
        if s % 8 == 4:
            out[start:start + seg] += lowpass(noise(seg), 0.6) * env(seg, 0.001, 0.05) * 0.45
        if s % 2 == 1:
            out[start:start + seg] += noise(seg) * env(seg, 0.001, 0.012) * 0.12
    write("music_loop", out, 0.55)


def traffic_ambience():
    t = t_axis(6.0)
    rumble = lowpass(noise(len(t)), 0.02) * (0.7 + 0.3 * np.sin(2 * np.pi * 0.25 * t))
    hiss = lowpass(noise(len(t)), 0.3) * 0.08
    x = rumble + hiss
    # Crossfade the loop seam.
    fade = int(SR * 0.5)
    x[:fade] = x[:fade] * np.linspace(0, 1, fade) + x[-fade:] * np.linspace(1, 0, fade)
    write("traffic_amb", x[:-fade], 0.35)


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    sfx()
    music()
    traffic_ambience()
    print("wrote", sorted(os.listdir(OUT)))
